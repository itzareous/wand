import AppKit
import Observation

struct ClipItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String
    var appName: String?
    var date = Date()
}

/// Remembers text copied on this Mac. Saved only on this Mac; never sent anywhere.
/// Skips items password managers mark as concealed or transient.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var items: [ClipItem] = []
    var isEnabled: Bool {
        didSet {
            UserDefaults.standard.set(isEnabled, forKey: Self.enabledKey)
            isEnabled ? startWatching() : stopWatching()
            onEnabledChange?()
        }
    }
    @ObservationIgnored var onEnabledChange: (() -> Void)?
    /// Name of the app in front, for labelling where a clip came from.
    @ObservationIgnored var currentAppName: (() -> String?)?

    static let maxItems = 100
    private static let maxLength = 20_000
    private static let enabledKey = "clipboard.enabled"
    /// Markers from nspasteboard.org that password managers and others set on secrets.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var ignoreChangeCount: Int?

    private static var fileURL: URL {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Wand", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("clipboard.json")
    }

    init() {
        isEnabled = UserDefaults.standard.bool(forKey: Self.enabledKey)
        if let data = try? Data(contentsOf: Self.fileURL),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
        if isEnabled { startWatching() }
    }

    /// Puts an item back on the clipboard (and at the top of the history) without re-recording it.
    func copyToPasteboard(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        ignoreChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        var moved = item
        moved.date = Date()
        items.removeAll { $0.id == item.id }
        items.insert(moved, at: 0)
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items = []
        save()
    }

    private func startWatching() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    private func stopWatching() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        if pasteboard.changeCount == ignoreChangeCount { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxLength else { return }
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text, appName: currentAppName?()), at: 0)
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
        save()
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: Self.fileURL, options: [.atomic, .completeFileProtection])
    }
}
